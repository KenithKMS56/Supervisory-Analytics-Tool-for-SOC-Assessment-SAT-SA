    lines += ["", *verdicts, "",
              (f"Entity ranking by number of baseline flags (ties averaged): precision@k {_ci(bh, bk)}; "
               f"engine: {_ci(t['rank_hits'], t['rank_k'])}."), ""]

    lines += ["## 4. Ablation: one rule family removed", "",
              "The same stores, scored again without one family (dry run). Defects of the removed family",
              "count as missed. Removing the systemic detector changes no per-entity finding; its own",
              "result is in Section 2.", "",
              "| Configuration | Recall | Precision | False positives | Clean entities flagged | Ranking precision@k |",
              "|---|---|---|---:|---|---|",
              (f"| All 20 rules | {_ci(t['tp'], t['tp'] + t['fn'])} | {_ci(t['tp'], t['tp'] + t['fp'])} | {t['fp']:g} | "
               f"{t['clean_flagged']:g}/{t['clean_entities']:g} | {_ci(t['rank_hits'], t['rank_k'])} |")]
    for fam, label in FAMILIES.items():
        a = agg["ablation"][fam]
        lines.append(f"| Without {label} | {_ci(a['tp'], a['tp'] + a['fn'])} | {_ci(a['tp'], a['tp'] + a['fp'])} | "
                     f"{a['fp']:g} | {a['clean_flagged']:g}/{t['clean_entities']:g} | {_ci(a['rank_hits'], a['rank_k'])} |")

    lines += ["", "## 5. Threshold sweep (+/-20%, one threshold at a time)", "",
              "For each tunable threshold, in how many seeds a 20% move changed which entities the rule flags,",
              "and how many defects it lost and false alarms (decoys included) it added in total.", "",
              "| Rule | Threshold | Move | Seeds changed | Defects lost | False alarms added |", "|---|---|---|---:|---:|---:|"]
    for (rule, param, change), s2 in sorted(agg["sweep"].items()):
        if s2["runs_changed"]:
            lines.append(f"| {rule} | `{param}` | {change} | {s2['runs_changed']} of {s2['runs']} | {s2['new_fn']} | {s2['new_fp']} |")
    lines += ["", "Moves not listed changed nothing in any seed.", ""]

    lines += ["## 6. Ground truth relabelled by the documented criterion", "",
              "| Rule: built as -> labelled | Times |", "|---|---:|"]
    for key, n in agg["relabelled"].items():
        lines.append(f"| {key} | {n} |")
    if not agg["relabelled"]:
        lines.append("| none | 0 |")
    lines += ["", "A *baseline -> defect* row means an entity that nobody built a defect into meets the",
              "documented criterion by chance. These count as defects in Section 2: the rule is right to",
              "flag them under its own specification, which says something about the specification",
              "(`docs/threshold_rationale.md`).", "",
              "## 7. Per seed", "", "| Seed | Defects | Decoys | Detected | False positives | Missed | Seconds |",
              "|---:|---:|---:|---:|---:|---|---:|"]
    for r in results:
        e = r["engine"]
        lines.append(f"| {r['seed']} | {r['defects']} | {r['decoys']} | {e['tp']} | {e['fp']} | {', '.join(e['missed']) or '-'} | {r['seconds']} |")
    lines += ["", "False positives per seed: " + "; ".join(
        f"{r['seed']}: {', '.join(r['engine']['false_positives']) or '-'}" for r in results), ""]
    lines += WHAT_THIS_PROVES
    return "\n".join(lines) + "\n"


