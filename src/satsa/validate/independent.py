FAMILIES = {"EG": "Execution gaps (EG01-EG12)", "NS": "Negative space (NS01-NS08)"}


def _precision_at_k(ranked: list[tuple[str, float]], positives: set[str]) -> tuple[float, int]:
    """Expected number of positives in the top k (k = number of positives), averaging over
    the order of tied scores at the cut-off. Returns (expected hits, k)."""
    k = len(positives)
    if k == 0:
        return 0.0, 0
    ordered = sorted(ranked, key=lambda x: -x[1])
    hits, taken, i = 0.0, 0, 0
    while i < len(ordered) and taken < k:
        tie = [e for e, s in ordered if s == ordered[i][1]]
        slots = min(k - taken, len(tie))
        pos_in_tie = sum(1 for e in tie if e in positives)
        hits += slots * pos_in_tie / len(tie)
        taken += slots
        i += len(tie)
    return hits, k


def _score_pairs(found: set[tuple[str, str]], gt: dict[str, Any]) -> dict[str, Any]:
    defects = {(d["entity_id"], d["rule_id"]) for d in gt["defects"]}
    decoys = {(d["entity_id"], d["rule_id"]) for d in gt["decoys"]}
    clean = set(gt["clean_entities"])
    per_rule: dict[str, dict[str, int]] = defaultdict(lambda: {"tp": 0, "fn": 0, "fp": 0, "decoys": 0, "decoys_flagged": 0})
    for pair in defects:
        per_rule[pair[1]]["tp" if pair in found else "fn"] += 1
    for pair in found - defects:
        per_rule[pair[1]]["fp"] += 1
    for pair in decoys:
        per_rule[pair[1]]["decoys"] += 1
        per_rule[pair[1]]["decoys_flagged"] += pair in found
    fp = found - defects
    return {
        "tp": len(found & defects), "fn": len(defects - found), "fp": len(fp),
        "fp_on_decoys": len(fp & decoys), "fp_on_clean": sum(1 for e, _ in fp if e in clean),
        "decoys": len(decoys), "decoys_flagged": len(found & decoys),
        "clean_entities": len(clean), "clean_flagged": len({e for e, _ in found if e in clean}),
        "missed": sorted(f"{e}:{r}" for e, r in defects - found),
        "false_positives": sorted(f"{e}:{r}" for e, r in fp),
        "per_rule": {r: dict(v) for r, v in sorted(per_rule.items())},
    }


def run_seed(seed: int, rules_config: str = "config/rules.yaml", sweep: bool = True) -> dict[str, Any]:
    """Generate, ingest and assess one independent scenario; score the engine and baselines."""
    started = time.perf_counter()
    with tempfile.TemporaryDirectory(prefix="satsa-ind-") as tmp:
        tmp_path = Path(tmp)
        csv_dir, gt_path = IndependentScenarioGenerator(seed).save(tmp_path / "gen")
        gt = json.loads(gt_path.read_text(encoding="utf-8"))
        duck = DuckDBStore(tmp_path / "store")
        sql = SQLiteStore(tmp_path / "store" / "independent.db")
        try:
            IngestionPipeline(duck, sql).ingest_directory(csv_dir)
            runner = AssessmentRunner(duck, sql, rules_config_path=rules_config)
            res = runner.run_assessment(period="INDEPENDENT", actor="cli:validate-independent")
            run_id = res["run_id"]
            rows = sql.conn.execute("SELECT entity_id, rule_id FROM findings WHERE run_id = ?", (run_id,)).fetchall()
            found = {(r["entity_id"], r["rule_id"]) for r in rows}
            engine = _score_pairs(found, gt)

            defect_entities = {d["entity_id"] for d in gt["defects"]}
            scores = [(e, float(v["risk_index"])) for e, v in res["entity_scores"].items()]
            hits, k = _precision_at_k(scores, defect_entities)
            engine["ranking"] = {"hits": hits, "k": k}

            # Design margin: recall for share-based defects by how far over the threshold they were built.
            margins = []
            for d in gt["defects"]:
                f = (d.get("measured") or {}).get("design_factor")
                if f is not None:
                    margins.append({"rule_id": d["rule_id"], "factor": f, "detected": (d["entity_id"], d["rule_id"]) in found})
            engine["margins"] = margins

            # Systemic: expected groups detected, decoy pairs flagged.
            systemic = sql.get_systemic_findings(run_id)
            got = [(s["rule_id"], s.get("shared_value"), set(s.get("entity_ids") or [])) for s in systemic]
            exp = gt["systemic_expected"]
            sys_tp = sum(1 for x in exp if any(r == x["rule_id"] and set(x["entities"]) <= ents for r, _v, ents in got))
            sys_fp = sum(1 for r, v, ents in got if not any(r == x["rule_id"] and set(x["entities"]) <= ents for x in exp))
            engine["systemic"] = {"expected": len(exp), "detected": sys_tp, "other_systemic_findings": sys_fp,
                                  "decoy_pairs_flagged": sum(1 for x in gt["systemic_decoys"]
                                                             if any(r == x["rule_id"] and set(x["entities"]) <= ents for r, _v, ents in got))}

            # Baselines on the same store.
            base_flags = run_baselines(duck)
            baselines = {}
            for name, meta in BASELINES.items():
                rule = meta["maps_to"]
                pairs = {(e, rule) for e in base_flags[name]}
                truth = {(d["entity_id"], d["rule_id"]) for d in gt["defects"] if d["rule_id"] == rule}
                decoys = {(d["entity_id"], d["rule_id"]) for d in gt["decoys"] if d["rule_id"] == rule}
                engine_pairs = {p for p in found if p[1] == rule}
                baselines[name] = {
                    "maps_to": rule,
                    "baseline": {"tp": len(pairs & truth), "fp": len(pairs - truth), "fn": len(truth - pairs),
                                 "decoys_flagged": len(pairs & decoys), "flagged": len(pairs)},
                    "engine": {"tp": len(engine_pairs & truth), "fp": len(engine_pairs - truth), "fn": len(truth - engine_pairs),
                               "decoys_flagged": len(engine_pairs & decoys), "flagged": len(engine_pairs)},
                }
            flag_count = {e: 0.0 for e in res["entity_scores"]}
            for flagged in base_flags.values():
                for e in flagged:
                    flag_count[e] = flag_count.get(e, 0.0) + 1
            b_hits, b_k = _precision_at_k(list(flag_count.items()), defect_entities)
            baselines["_ranking"] = {"hits": b_hits, "k": b_k}

            # Ablation: the same store, scored without one rule family (dry run, nothing persisted).
            ablation = {}
            for fam in FAMILIES:
                abl = AssessmentRunner(duck, sql, rules_config_path=rules_config)
                abl.registry.rules = {rid: r for rid, r in abl.registry.rules.items() if not rid.startswith(fam)}
                dry = abl.run_assessment(period="ABLATION", dry_run=True, refresh_tables=False)
                abl_found = {(f["entity_id"], f["rule_id"]) for f in dry["findings"]}
                scored = _score_pairs(abl_found, gt)
                a_hits, a_k = _precision_at_k([(e, float(v["risk_index"])) for e, v in dry["entity_scores"].items()],
                                              defect_entities)
                scored["ranking"] = {"hits": a_hits, "k": a_k}
                scored["systemic_findings"] = dry.get("systemic_findings_count", 0)
                ablation[fam] = scored

            sens = None
            if sweep:
                harness = ValidationHarness(duck, sql, gt_path)
                raw = harness.evaluate_threshold_sensitivity(rules_config)
                sens = [{"rule_id": r["rule_id"], "param": r["param"], "change": r["change"], "changed": r["changed"],
                         "new_fn": sorted(set(r["outcome"]["fn"]) - set(r["baseline_outcome"]["fn"])),
                         "new_fp": sorted(set(r["outcome"]["fp"]) - set(r["baseline_outcome"]["fp"]))}
                        for r in raw["rows"]]
        finally:
            duck.close()
            sql.close()
    return {
        "seed": seed, "seconds": round(time.perf_counter() - started, 1),
        "defects": len(gt["defects"]), "decoys": len(gt["decoys"]),
        "relabelled": gt["relabelled"], "incidental": [f"{d['entity_id']}:{d['rule_id']}" for d in gt["defects"]
                                                        if d["defect_type"] in ("incidental", "decoy_met_criterion")],
        "engine": engine, "baselines": baselines, "ablation": ablation, "sensitivity": sens,
    }


# ------------------------------------------------------------------ aggregation and report


def _ci(num: float, den: float) -> str:
    """Percentage, counts and 95% Wilson interval. A fractional numerator (ranking hits averaged
    over tied scores) is rounded to the nearest whole count for the interval only."""
    if not den:
        return "n/a"
    iv = wilson_interval(round(num), int(den))
    pct = 100.0 * num / den
    shown = f"{num:g}" if float(num).is_integer() else f"{num:.1f}"
    return f"{pct:.1f}% ({shown}/{den:g}; 95% CI {iv[0] * 100:.1f}-{iv[1] * 100:.1f}%)" if iv else f"{pct:.1f}%"


def aggregate(results: list[dict[str, Any]]) -> dict[str, Any]:
    tot: dict[str, float] = defaultdict(float)
    per_rule: dict[str, dict[str, int]] = defaultdict(lambda: defaultdict(int))
    for r in results:
        e = r["engine"]
        for key in ("tp", "fn", "fp", "fp_on_decoys", "fp_on_clean", "decoys", "decoys_flagged", "clean_entities", "clean_flagged"):
            tot[key] += e[key]
        tot["rank_hits"] += e["ranking"]["hits"]
        tot["rank_k"] += e["ranking"]["k"]
        for rule, c in e["per_rule"].items():
            for key, v in c.items():
                per_rule[rule][key] += v
    base: dict[str, dict[str, dict[str, int]]] = {}
    for name in BASELINES:
        base[name] = {"baseline": defaultdict(int), "engine": defaultdict(int)}
        for r in results:
            for side in ("baseline", "engine"):
                for key, v in r["baselines"][name][side].items():
                    base[name][side][key] += v
    base_rank = (sum(r["baselines"]["_ranking"]["hits"] for r in results), sum(r["baselines"]["_ranking"]["k"] for r in results))
    abl: dict[str, dict[str, float]] = {}
    for fam in FAMILIES:
        a: dict[str, float] = defaultdict(float)
        for r in results:
            x = r["ablation"][fam]
            for key in ("tp", "fn", "fp", "fp_on_decoys", "fp_on_clean", "clean_flagged"):
                a[key] += x[key]
            a["rank_hits"] += x["ranking"]["hits"]
            a["rank_k"] += x["ranking"]["k"]
            a["systemic_findings"] += x["systemic_findings"]
        abl[fam] = dict(a)
    systemic: dict[str, int] = defaultdict(int)
    for r in results:
        for name, v in r["engine"]["systemic"].items():
            systemic[name] += v
    margins: dict[str, list[int]] = {"1.08-1.30": [0, 0], "1.30-1.60": [0, 0], "1.60-1.90": [0, 0]}
    for r in results:
        for m in r["engine"]["margins"]:
            b = "1.08-1.30" if m["factor"] < 1.30 else "1.30-1.60" if m["factor"] < 1.60 else "1.60-1.90"
            margins[b][0] += m["detected"]
            margins[b][1] += 1
    sweep: dict[tuple[str, str, str], dict[str, Any]] = {}
    for r in results:
        for row in r["sensitivity"] or []:
            cell = (row["rule_id"], row["param"], row["change"])
            s = sweep.setdefault(cell, {"runs_changed": 0, "new_fn": 0, "new_fp": 0, "runs": 0})
            s["runs"] += 1
            s["runs_changed"] += row["changed"]
            s["new_fn"] += len(row["new_fn"])
            s["new_fp"] += len(row["new_fp"])
    relabelled: dict[str, int] = defaultdict(int)
    for r in results:
        for x in r["relabelled"]:
            relabelled[f"{x['rule_id']}: {x['built_as']} -> {x['labelled']}"] += 1
    return {"totals": dict(tot), "per_rule": {k: dict(v) for k, v in sorted(per_rule.items())},
            "baselines": {k: {s: dict(v) for s, v in d.items()} for k, d in base.items()}, "baseline_ranking": base_rank,
            "ablation": abl, "systemic": dict(systemic), "margins": margins, "sweep": sweep,
            "relabelled": dict(sorted(relabelled.items()))}


