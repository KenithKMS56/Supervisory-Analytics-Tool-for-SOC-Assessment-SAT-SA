"""Validation on the independent generator: the engine, three naive baselines, a family
ablation, the +/-20% threshold sweep and Wilson intervals, over many seeds.

`satsa validate-independent` runs this. Each seed is generated by
`satsa.synth.independent.IndependentScenarioGenerator`, ingested and assessed in its own
temporary store, so nothing touches `data/`. Every figure in the report is computed here from
those runs.
"""

