        b_rec = b["tp"] / max(b["tp"] + b["fn"], 1)
        e_rec = e["tp"] / max(e["tp"] + e["fn"], 1)
        b_pre = b["tp"] / max(b["tp"] + b["fp"], 1)
        e_pre = e["tp"] / max(e["tp"] + e["fp"], 1)
        rec = "ties" if abs(b_rec - e_rec) < 1e-9 else ("wins" if b_rec > e_rec else "loses")
